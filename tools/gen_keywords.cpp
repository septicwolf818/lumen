// Generates src/keywords_data.inc from data/keywords.json at build time.
// The JSON is embedded verbatim as a raw string so the C++ lexer can parse it
// with the already-vendored nlohmann/json - no extra dependency and no runtime
// file lookup, so the installed binary is self-contained.
#include <cstdio>
#include <fstream>
#include <sstream>
#include <string>

int main(int argc, char** argv) {
    if (argc < 3) {
        std::fprintf(stderr, "usage: gen_keywords INPUT.json OUTPUT.inc\n");
        return 2;
    }
    std::ifstream in(argv[1], std::ios::binary);
    if (!in) {
        std::fprintf(stderr, "cannot open %s\n", argv[1]);
        return 1;
    }
    std::stringstream ss;
    ss << in.rdbuf();
    std::string json = ss.str();

    // Pick a raw-string delimiter that does not occur in the data.
    std::string delim = "MDKW";
    while (json.find(")" + delim + "\"") != std::string::npos) delim += "X";

    std::ofstream out(argv[2], std::ios::binary);
    if (!out) {
        std::fprintf(stderr, "cannot write %s\n", argv[2]);
        return 1;
    }
    out << "// Auto-generated by tools/gen_keywords.cpp - do not edit.\n";
    out << "static const char kKeywordsJson[] = R\"" << delim << "(";
    out.write(json.data(), static_cast<std::streamsize>(json.size()));
    out << ")" << delim << "\";\n";
    return 0;
}
