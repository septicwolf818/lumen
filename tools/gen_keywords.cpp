// Build-time generator for src/keywords_data.inc from data/keywords.json.
// Embeds the JSON as raw-string literals so the lexer parses it with the
// vendored nlohmann/json - no extra dependency, no runtime file lookup.
#include <algorithm>
#include <cstdio>
#include <fstream>
#include <sstream>
#include <string>

int main(int argc, char** argv) {
    if (argc < 3) {
        std::fprintf(stderr, "usage: gen_keywords INPUT.json OUTPUT.inc\n");
        return 2;
    }
    std::ifstream in(argv[1], std::ios::binary);
    if (!in) {
        std::fprintf(stderr, "cannot open %s\n", argv[1]);
        return 1;
    }
    std::stringstream ss;
    ss << in.rdbuf();
    std::string json = ss.str();

    // Pick a raw-string delimiter that does not occur in the data.
    std::string delim = "MDKW";
    while (json.find(")" + delim + "\"") != std::string::npos) delim += "X";

    std::ofstream out(argv[2], std::ios::binary);
    if (!out) {
        std::fprintf(stderr, "cannot write %s\n", argv[2]);
        return 1;
    }
    out << "// Auto-generated by tools/gen_keywords.cpp - do not edit.\n";
    // Emit chunk literals: one literal longer than the compiler's minimum
    // supported length (65536) is not portable, and keywords.cpp joins the
    // chunks into one std::string before parsing.
    constexpr size_t kChunk = 32768;
    if (json.empty()) {
        out << "static const char* const kKeywordsJsonChunks[] = { nullptr };\n";
        return 0;
    }
    out << "static const char* const kKeywordsJsonChunks[] = {\n";
    for (size_t off = 0; off < json.size(); off += kChunk) {
        size_t n = std::min(kChunk, json.size() - off);
        out << "    R\"" << delim << "(";
        out.write(json.data() + off, static_cast<std::streamsize>(n));
        out << ")" << delim << "\",\n";
    }
    out << "    nullptr\n};\n";  // sentinel: the joiner stops at the first null
    return 0;
}
